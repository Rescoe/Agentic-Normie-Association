/**
 * workStore.ts — Persistence for ANA autonomous work creation.
 *
 * Works go through a state machine:
 *   PROPOSED → VOTE_OPEN → VOTE_TALLIED → BRIEFING → CREATING
 *     → VALIDATING → PUBLISHING → PUBLISHED
 *   (or → REJECTED at any vote/validation step)
 *
 * Storage: separate Neon kv_store row ("work-store" key, not mixed with salon store).
 * The HTML artifact stored on-chain is built by buildWorkHtml() — no IPFS, all on Base.
 */

import fs   from "fs";
import path from "path";
import { CONTRACT_ADDRESSES } from "@/lib/contracts";

// ─── Types ────────────────────────────────────────────────────────────────────

export type WorkState =
  | "PROPOSED"
  | "VOTE_OPEN"
  | "VOTE_TALLIED"
  | "BRIEFING"
  | "CREATING"
  | "VALIDATING"
  | "PUBLISHING"
  | "PUBLISHED"
  | "REJECTED"
  // Circuit breaker (Sept 2026 pérennisation pass): a work that fails
  // similarly 3 times in a row pauses here instead of looping CREATING <->
  // VALIDATING forever — see stepNeedsRethink() in work-lifecycle. Not a
  // rejection: the work resumes automatically (new author + fresh brief) once
  // the cause looks like a creative mismatch, or waits on a human dev-request
  // if the cause looks technical (a structural validator failure).
  | "NEEDS_RETHINK";

export const ACTIVE_STATES: WorkState[] = [
  "PROPOSED", "VOTE_OPEN", "VOTE_TALLIED",
  "BRIEFING", "CREATING", "VALIDATING", "PUBLISHING", "NEEDS_RETHINK",
];

export interface WorkVote {
  tokenId:      number;
  name:         string;
  vote:         "yes" | "no" | "abstain";
  reason:       string;
  votedAt:      number;
  interestedIn?: "author" | "curator" | "none";
}

export interface StateHistoryEntry {
  state: WorkState;
  at:    number;
  note?: string;
}

export interface ANAWork {
  id:             string;
  proposedBy:     number;
  proposedByName: string;
  proposedAt:     number;
  title:          string;
  proposal:       string;
  suggestedForm?: string;  // form suggested by the Proposer at PROPOSED time — Rapporteur should honor it
  state:          WorkState;
  stateHistory:   StateHistoryEntry[];

  // Voting
  votes:         WorkVote[];
  voteOpenedAt?: number;
  voteClosedAt?: number;
  voteResult?:   "passed" | "rejected";
  yesCount?:     number;
  noCount?:      number;
  absCount?:     number;
  totalVoters?:  number;
  // Cumulative vote-attempt counters across every stepVoteOpen() tick this
  // vote window has seen — an invalid LLM output or provider error is a
  // technical failure, never folded into yes/no/abstain (see voting.ts).
  // Persisted into vote_metrics (voteMetricsStore.ts) once the window closes.
  voteInvalidOutputs?: number;
  voteProviderErrors?: number;
  voteRetries?:        number;

  // Roles (assigned after vote passes) — the Normie actually dispatched to do the work
  rapporteurTokenId?: number;
  authorTokenId?:     number;
  curatorTokenId?:    number;
  rapporteurName?:    string;
  authorName?:        string;
  curatorName?:       string;

  // Elected officer on duty at dispatch time (arbiter) — distinct from the dispatched
  // executor above once the bureau is elected. Captured now for future reputation scoring
  // of arbitration quality; not yet used by any scoring logic.
  rapporteurArbiterTokenId?: number;
  authorArbiterTokenId?:     number;
  curatorArbiterTokenId?:    number;

  // Creative phases
  artForm?:        string;   // "haiku"|"sonnet"|"poeme"|"prose"|"manifeste"|"html-canvas"|"html-p5js"|"html-threejs"|"html-webgl"
  ambitionLevel?:  "quick" | "standard" | "ambitious"; // set by the Rapporteur — scales how much effort/token budget the Author gets
  editionPrice?:   string;   // ETH price string, e.g. "0.01"
  editionSupply?:  number;   // Number of tradeable ERC-721 editions (1-100)
  brief?:          string;
  briefAt?:        number;
  artworkText?:    string;  // poem / manifesto / standalone HTML generated by Author
  artworkAt?:      number;
  validationNote?: string;
  revisionCount?:  number;
  pipelineFailCount?: number; // consecutive advanceWork() failures in the current state — auto-rejects past MAX_PIPELINE_FAILS
  // Circuit breaker bookkeeping (see NEEDS_RETHINK state above).
  similarFailureStreak?: number;
  needsRethinkReason?:   "technical" | "creative";

  // Post-publication community critique (non-creator Normies react/debate in the
  // work's archived salon for a limited window) — see openCritiqueWindow() in
  // salonStore.ts and runCritiquePhase() in work-lifecycle/route.ts.
  critiqueSummary?:   string;
  critiqueSummaryAt?: number;

  // On-chain
  txHash?:           string;
  onChainWorkId?:    number;
  publishedAt?:      number;
  collectionAddress?: string;  // NormieCollection deployed for this work (set after mint)
  editionTokenId?:    number;  // token #0 minted in that collection

  // Meta
  salonId?:        string;
  isBurnMemorial?: boolean;
  burnedTokenId?:  number;

  // Celebration sponsorship (CelebrationRegistry on-chain) — populated when this
  // work honors one or more burned/transformed Normies. Each id is wired to this
  // work's onChainWorkId/collectionAddress once published (see stepPublishing's
  // linkCelebrations call), enabling the honored wallet(s) to claim a free edition.
  celebrationIds?: number[];

  // Founding work (AG constitutive)
  isFoundingWork?:    boolean;
  foundingContext?:   Array<{ name: string; content: string; timestamp: number }>;
  allElectedRoles?:   Array<{ roleLabel: string; tokenId: number; name: string }>;

  // Memorial visual (artForm "pixel-drawing") — generated instantly at
  // creation (memorialArt.ts, no LLM/human involved, see check-burns.ts /
  // request-memorial.ts) rather than produced later in CREATING. drawPixels/
  // drawCanvasW/drawCanvasH are the raw grayscale bytes proof-of-draw reads
  // via GET /api/ana-art/feed once the work is PUBLISHED; artworkText holds a
  // BMP-wrapped copy for the certificate's <img> tag (a rendering
  // convenience, not the source proof-of-draw consumes). Moderation for this
  // artForm is the same member vote every other work goes through
  // (stepVoteOpen/stepVoteTallied), just running after creation instead of
  // before it — see stepVoteTallied's early PUBLISHING branch.
  drawPixels?:       string;
  drawCanvasW?:      number;
  drawCanvasH?:      number;
  // The proposer's own artist statement about this specific piece (LLM,
  // written alongside the shapes — see memorialArt.ts). Gallery/certificate
  // only: never sent to proof-of-draw (GET /api/ana-art/feed omits it).
  cartelText?:       string;

  // Shared ANAMemorials contract (replaces the old one-ANAEditions-per-memorial
  // pattern for every memorial created after this field existed — see
  // memorialPublisher.ts, batch-memorial/route.ts, request-memorial/route.ts).
  // A memorial with memorialKind == null predates this and stays on the old
  // deployCollection/publish/initialize rails (workPublisher.ts) — the two
  // coexist indefinitely, discriminated by this field's presence.
  burnedTokenIds?:          number[]; // plural — a batch honors several; burnedTokenId (singular) kept for display
  memorialKind?:            "batch" | "requested" | "milestone";
  memorialTier?:            1 | 2 | 3; // "requested" only
  // "milestone" only — a collective monument for every burn ANA has honored
  // up to a 1000-burn threshold (see milestone-memorial/route.ts). burnedTokenIds
  // on a milestone work is only a small representative sample (personas/flavor
  // for the LLM prompt) — memorialTotalBurnedAtMilestone is the true count the
  // piece actually honors, and memorialMilestoneNumber which threshold this is
  // (1 = first 1000 burns, 2 = first 2000, ...), used to gate re-triggering.
  memorialMilestoneNumber?:          number;
  memorialTotalBurnedAtMilestone?:   number;
  memorialPublicSupply?:    number;
  memorialRequesterSupply?: number;
  memorialRequesterAddr?:   string;
  memorialOpenEnded?:       boolean;
  memorialClaimDurationSeconds?: number;
  // burnedTokenId -> resolved last-owner wallet, one guaranteed free ANAMemorials
  // claim per entry (see ANAMemorials.sol's reservedClaims — structurally
  // separate from public/requester pools, never exhausted by their sales).
  reservedClaimRecipients?: Record<number, string>;
  onChainMemorialId?:       number; // series index in the shared ANAMemorials contract
  reservedClaimsAdded?:     boolean; // guards against re-adding (wasted gas) on a PUBLISHING retry
  // Same idempotency guard, for addHonoredTokenIds() — "milestone" monuments
  // only (batch/requested memorials get their honored-list populated as a
  // side effect of reservedClaimRecipients above, via addReservedClaims).
  honoredTokenIdsAdded?:    boolean;
  // Proof the requester paid for a "requested" memorial BEFORE it was created
  // (ANAMemorials.payForRequest(), verified in request-memorial/route.ts) — the relayer
  // is compensated for creation cost regardless of whether the memorial is
  // ever voted through or the requester later claims their edition. Also
  // used to reject a reused/replayed payment transaction.
  memorialPaymentTxHash?:  string;
  // Set once the relayer has auto-delivered the requester's own edition
  // (deliverRequesterEditionOnChain, best-effort) — guards against retrying
  // a delivery that already succeeded on a PUBLISHING retry. Absence doesn't
  // mean delivery failed forever: the requester can always self-claim.
  requesterEditionDelivered?: boolean;
}

interface DispatchRotation {
  author:     number; // cursor into the sorted member-tokenId list, advances on each dispatch
  curator:    number;
  rapporteur: number;
  reviewer:   number;
}

// ─── Constants ────────────────────────────────────────────────────────────────

export const VOTE_WINDOW_MS = 24 * 60 * 60 * 1000; // 24h max for voting
// Memorials are already fully created (instant, deterministic art — see
// memorialArt.ts) by the time their vote opens, and the whole burn -> vote ->
// publish pipeline is budgeted at ~4h end to end — a 24h fallback window
// would blow that budget if even one member's vote fails/stalls. In practice
// stepVoteOpen resolves in a single tick once every member has voted; this
// is only the fallback for stragglers.
// Was 90 min — with tallyVotes() now passing a memorial on a tie (including
// 0/0), there's no need for a long window to accumulate real "yes" votes; it
// only needs to give genuine "no" votes a chance to override the default
// pass. 20 min plus the more frequent salon-exchange piggyback advance
// (src/app/api/keeper/salon-exchange/route.ts) is enough for that.
export const CELEBRATION_VOTE_WINDOW_MS = 20 * 60 * 1000;

// One Neon row per work ("work:<id>"), not one giant blob for the whole
// list. Rebuilt from scratch (Sept 2026 cost audit, 2nd pass) rather than
// migrated -- the project was already about to wipe every work as part of a
// full contract redeploy, so there was no existing data worth preserving
// through a migration. The old single-blob model meant ANY change to ANY
// one work (a single vote, a state advance) rewrote the ENTIRE list back to
// Neon -- with the list at ~1.4MB for just 15 works, that's the single
// biggest cost driver this audit found. Per-row storage means a write's cost
// is proportional to that one work's own size, never the whole list's.
//
// listWorks() (and everything built on it: getActiveWorks, getFoundingWork,
// getWorkBySalonId, getSalonWorkOutcomes) still needs every work's full
// data, so it still costs one query returning N rows -- same as reading one
// blob, no worse. What's gone is the WRITE amplification: updateWork(),
// advanceState(), addVote() now each touch exactly one row.
const WORK_KEY_PREFIX = "work:";
const DISPATCH_KEY    = "dispatch-rotation";
const DATA_FILE       = path.join(process.cwd(), "data", "works.json");

// Local dev fallback (no NEON_DB_ANA configured) keeps the old single-file
// shape -- there's no Neon cost to optimize against on a local disk, so
// splitting local dev storage into one file per work would only add
// complexity for zero benefit.
interface LocalWorkStore {
  works:             Record<string, ANAWork>;
  dispatchRotation?: DispatchRotation;
}

declare global {
  // eslint-disable-next-line no-var
  var __anaWorkStore: LocalWorkStore | undefined;
}

async function useNeon(): Promise<boolean> {
  const { USE_NEON } = await import("./db");
  return USE_NEON;
}

// Once a work reaches one of these states it is done changing, and its full
// on-chain record already exists (the certificate built in stepPublishing
// bakes in every vote reason and the whole state history permanently — see
// buildWorkHtml below).
const TERMINAL_STATES: WorkState[] = ["PUBLISHED", "REJECTED"];

/**
 * Trims the bulkiest free-text fields (vote reasons, state-history notes) on
 * terminal-state works before they're written to Neon. artworkText (the
 * actual creative output) and every summary field the gallery displays
 * (yesCount, title, artForm...) are left untouched.
 */
function pruneWorkForStorage(w: ANAWork): ANAWork {
  if (!TERMINAL_STATES.includes(w.state)) return w;
  return {
    ...w,
    votes: (w.votes ?? []).map(v =>
      v.reason.length > 60 ? { ...v, reason: v.reason.slice(0, 60) + "…" } : v
    ),
    stateHistory: (w.stateHistory ?? []).map(h => h.note ? { state: h.state, at: h.at } : h),
  };
}

// ─── In-process read cache (Neon mode only) ───────────────────────────────────
// Caches the full "list every work" query for a short window -- avoids
// repeating that one query for every sub-call within the same request burst
// or warm Lambda invocation. A single work's read/write (getWork, updateWork,
// advanceState, addVote) never goes through this cache: it targets its own
// row directly, which is now cheap enough not to need caching at all.
const CACHE_TTL_MS = 15_000;
let _listCache: { works: Record<string, ANAWork>; at: number } | null = null;

/** Drops the in-process list cache immediately — used after an out-of-band
 * write (e.g. a full database wipe) so this warm Lambda instance doesn't
 * keep serving stale data for up to CACHE_TTL_MS. */
export function invalidateCache(): void { _listCache = null; }

async function neonListAllWorks(): Promise<Record<string, ANAWork>> {
  const works: Record<string, ANAWork> = {};
  try {
    const { kvListByPrefix } = await import("./db");
    const rows = await kvListByPrefix(WORK_KEY_PREFIX);
    for (const { key, value } of rows) {
      try {
        works[key.slice(WORK_KEY_PREFIX.length)] = JSON.parse(value) as ANAWork;
      } catch (e) {
        console.error(`[workStore] failed to parse ${key}:`, e);
      }
    }
  } catch (e) {
    console.error("[workStore] neonListAllWorks error:", e);
  }
  return works;
}

async function getAllWorks(): Promise<Record<string, ANAWork>> {
  if (await useNeon()) {
    if (_listCache && Date.now() - _listCache.at < CACHE_TTL_MS) return _listCache.works;
    const works = await neonListAllWorks();
    _listCache = { works, at: Date.now() };
    return works;
  }
  if (!global.__anaWorkStore) global.__anaWorkStore = fileLoad();
  return global.__anaWorkStore.works;
}

// ─── Local file I/O (dev fallback when NEON_DB_ANA is not set) ───────────────

function fileLoad(): LocalWorkStore {
  try {
    if (fs.existsSync(DATA_FILE)) {
      const s = JSON.parse(fs.readFileSync(DATA_FILE, "utf-8")) as LocalWorkStore;
      if (!s.works) s.works = {};
      return s;
    }
  } catch { /* empty */ }
  return { works: {} };
}

function fileSave(store: LocalWorkStore): void {
  try {
    fs.mkdirSync(path.dirname(DATA_FILE), { recursive: true });
    const tmp = DATA_FILE + ".tmp";
    fs.writeFileSync(tmp, JSON.stringify(store, null, 2), "utf-8");
    fs.renameSync(tmp, DATA_FILE);
  } catch (e) { console.error("[workStore] fileSave error:", e); }
}

// Single-work read: always a direct, targeted fetch -- cheaper than pulling
// every work just to find one, unlike the old single-blob model where there
// was no other option.
async function readOneWork(id: string): Promise<ANAWork | null> {
  if (await useNeon()) {
    try {
      const { kvGet } = await import("./db");
      const raw = await kvGet(WORK_KEY_PREFIX + id);
      return raw ? (JSON.parse(raw) as ANAWork) : null;
    } catch (e) {
      console.error(`[workStore] readOneWork(${id}) error:`, e);
      return null;
    }
  }
  return (await getAllWorks())[id] ?? null;
}

// Single-work write: touches only this one row/entry, never the rest of the
// list. `merge`, when given, re-reads the row immediately before writing and
// lets the caller reconcile against whatever is there right now -- the same
// spirit as the old blob-level anti-shrink check, just scoped down to one
// work instead of the entire list, and cheap enough to always do rather than
// being a special-cased safety net.
async function writeOneWork(
  id: string,
  fn: (w: ANAWork) => void,
  opts: { merge?: (fresh: ANAWork, working: ANAWork) => void } = {},
): Promise<ANAWork | null> {
  if (await useNeon()) {
    try {
      const { kvGet, kvSet } = await import("./db");
      const raw = await kvGet(WORK_KEY_PREFIX + id);
      if (!raw) return null;
      const work = JSON.parse(raw) as ANAWork;
      fn(work);
      if (opts.merge) {
        const freshRaw = await kvGet(WORK_KEY_PREFIX + id);
        if (freshRaw) opts.merge(JSON.parse(freshRaw) as ANAWork, work);
      }
      await kvSet(WORK_KEY_PREFIX + id, JSON.stringify(pruneWorkForStorage(work)));
      if (_listCache) _listCache.works[id] = work;
      return work;
    } catch (e) {
      console.error(`[workStore] writeOneWork(${id}) error:`, e);
      return null;
    }
  }
  const store = await (async () => { if (!global.__anaWorkStore) global.__anaWorkStore = fileLoad(); return global.__anaWorkStore; })();
  const work = store.works[id];
  if (!work) return null;
  fn(work);
  fileSave(store);
  return work;
}

// ─── Work CRUD ────────────────────────────────────────────────────────────────

export async function listWorks(): Promise<ANAWork[]> {
  return Object.values(await getAllWorks()).sort((a, b) => b.proposedAt - a.proposedAt);
}

export async function getWork(id: string): Promise<ANAWork | null> {
  return readOneWork(id);
}

export async function getActiveWorks(opts?: { excludeMemorials?: boolean }): Promise<ANAWork[]> {
  return (await listWorks()).filter(w =>
    ACTIVE_STATES.includes(w.state) && !(opts?.excludeMemorials && w.isBurnMemorial));
}

export async function createWork(
  params: Omit<ANAWork, "id" | "votes" | "stateHistory" | "state">,
  initialState: WorkState = "PROPOSED",
): Promise<ANAWork> {
  const id = `work_${Date.now()}_${Math.random().toString(36).slice(2, 7)}`;
  const work: ANAWork = {
    ...params,
    id,
    state: initialState,
    votes: [],
    stateHistory: [{ state: initialState, at: Date.now() }],
  };
  // A fresh row under a fresh id -- no read-modify-write needed, unlike the
  // old model where creating one work meant rewriting the entire list.
  if (await useNeon()) {
    try {
      const { kvSet } = await import("./db");
      await kvSet(WORK_KEY_PREFIX + id, JSON.stringify(work));
      if (_listCache) _listCache.works[id] = work;
    } catch (e) {
      console.error(`[workStore] createWork(${id}) error:`, e);
    }
  } else {
    if (!global.__anaWorkStore) global.__anaWorkStore = fileLoad();
    global.__anaWorkStore.works[id] = work;
    fileSave(global.__anaWorkStore);
  }
  console.log(`[workStore] created "${work.title}" (${id}) @ ${initialState}`);
  return work;
}

export async function getFoundingWork(): Promise<ANAWork | null> {
  const all = await listWorks();
  return all.find(w => w.isFoundingWork) ?? null;
}

/** Reverse lookup: the work whose creative process is hosted in this salon, if any. */
export async function getWorkBySalonId(salonId: string): Promise<ANAWork | null> {
  const all = await listWorks();
  return all.find(w => w.salonId === salonId) ?? null;
}

export type SalonWorkOutcome = "active" | "published" | "rejected";

/** Maps every salonId → its work's outcome, for enriching salon list responses in one pass. */
export async function getSalonWorkOutcomes(): Promise<Record<string, SalonWorkOutcome>> {
  const all = await listWorks();
  const map: Record<string, SalonWorkOutcome> = {};
  for (const w of all) {
    if (!w.salonId) continue;
    map[w.salonId] = w.state === "PUBLISHED" ? "published" : w.state === "REJECTED" ? "rejected" : "active";
  }
  return map;
}

export async function updateWork(id: string, updates: Partial<ANAWork>): Promise<void> {
  await writeOneWork(id, w => Object.assign(w, updates));
}

export async function advanceState(id: string, newState: WorkState, note?: string): Promise<void> {
  const updated = await writeOneWork(id, w => {
    w.state = newState;
    w.stateHistory.push({ state: newState, at: Date.now(), note });
  });
  if (updated) console.log(`[workStore] ${id} → ${newState}${note ? ` (${note})` : ""}`);
}

export async function addVote(id: string, vote: WorkVote): Promise<void> {
  await writeOneWork(id, w => {
    w.votes = w.votes.filter(v => v.tokenId !== vote.tokenId);
    w.votes.push(vote);
  }, {
    // Two votes for DIFFERENT personas can plausibly land close together
    // (overlapping keeper runs) -- fold in any vote the fresh row has that
    // our working copy doesn't, so a near-simultaneous second vote never
    // gets clobbered by the first one's write.
    merge: (fresh, working) => {
      for (const v of fresh.votes) {
        if (!working.votes.some(wv => wv.tokenId === v.tokenId)) working.votes.push(v);
      }
    },
  });
}

// ─── Burn tracking ────────────────────────────────────────────────────────────
//
// Deliberately its OWN Neon row ("burn-supply-tracker"), not a field on the
// ~1.4MB work-store blob. check-burns.yml runs hourly and unconditionally
// calls updateNormieSupply() (even when supply is unchanged) -- when this was
// stored on WorkStore.lastNormieSupply, that single-integer write triggered a
// full mutate(): a fresh 1.4MB neonLoad() (bypasses the read cache on
// purpose) plus a full 1.4MB neonSave(), on every single cron tick, for a
// value that only actually needs a few bytes. Confirmed (Sept 2026 audit) as
// ~3GB/month of Neon transfer from this one cron alone. A dedicated tiny key
// means this tracker's read/write cost stays proportional to its own size,
// completely decoupled from how large the works list grows.
const SUPPLY_FILE = path.join(process.cwd(), "data", "burn-supply.json");
let _supplyCache: number | null = null;

export async function getLastNormieSupply(): Promise<number | null> {
  if (await useNeon()) {
    try {
      const { kvGet } = await import("./db");
      const raw = await kvGet("burn-supply-tracker");
      return raw ? Number(raw) : null;
    } catch (e) {
      console.error("[workStore] getLastNormieSupply error:", e);
      return null;
    }
  }
  if (_supplyCache !== null) return _supplyCache;
  try {
    if (fs.existsSync(SUPPLY_FILE)) {
      _supplyCache = JSON.parse(fs.readFileSync(SUPPLY_FILE, "utf-8")).supply ?? null;
    }
  } catch { /* empty */ }
  return _supplyCache;
}

export async function updateNormieSupply(supply: number): Promise<void> {
  // Skip the write entirely when unchanged -- the common case on every
  // hourly tick where no burn happened.
  if (await getLastNormieSupply() === supply) return;
  if (await useNeon()) {
    try {
      const { kvSet } = await import("./db");
      await kvSet("burn-supply-tracker", String(supply));
    } catch (e) {
      console.error("[workStore] updateNormieSupply error:", e);
    }
    return;
  }
  _supplyCache = supply;
  try {
    fs.mkdirSync(path.dirname(SUPPLY_FILE), { recursive: true });
    fs.writeFileSync(SUPPLY_FILE, JSON.stringify({ supply }), "utf-8");
  } catch (e) { console.error("[workStore] burn-supply fileSave error:", e); }
}

// ─── Creative dispatch (round-robin) ──────────────────────────────────────────
//
// Once the bureau (Author/Curator/Rapporteur) is elected, those officers no
// longer author/curate/report every work themselves — they act as arbiters,
// and the actual creative work is dispatched across ALL registered members in
// rotation, so participation isn't limited to the 3 elected Normies. The
// rotation cursor is a single growing index per role over the sorted member
// roster; per-work exclusions (e.g. don't pick the same Normie for two roles
// on one work) are skipped without consuming their turn.
//
// This is a simple fairness mechanism for now. Once a reliable per-role
// reputation score exists, the elected officer's "arbitration" can become a
// real choice informed by that score instead of blind rotation.

export type DispatchRole = "author" | "curator" | "rapporteur" | "reviewer";

/**
 * Picks the next Normie tokenId for `role` from `candidates` (sorted ascending
 * by tokenId for determinism), skipping any tokenId in `exclude`, and persists
 * the advanced rotation cursor.
 */
const DEFAULT_ROTATION: DispatchRotation = { author: 0, curator: 0, rapporteur: 0, reviewer: 0 };

async function readDispatchRotation(): Promise<DispatchRotation> {
  if (await useNeon()) {
    try {
      const { kvGet } = await import("./db");
      const raw = await kvGet(DISPATCH_KEY);
      return raw ? (JSON.parse(raw) as DispatchRotation) : DEFAULT_ROTATION;
    } catch (e) {
      console.error("[workStore] readDispatchRotation error:", e);
      return DEFAULT_ROTATION;
    }
  }
  if (!global.__anaWorkStore) global.__anaWorkStore = fileLoad();
  return global.__anaWorkStore.dispatchRotation ?? DEFAULT_ROTATION;
}

async function writeDispatchRotation(rotation: DispatchRotation): Promise<void> {
  if (await useNeon()) {
    try {
      const { kvSet } = await import("./db");
      await kvSet(DISPATCH_KEY, JSON.stringify(rotation));
    } catch (e) {
      console.error("[workStore] writeDispatchRotation error:", e);
    }
    return;
  }
  if (!global.__anaWorkStore) global.__anaWorkStore = fileLoad();
  global.__anaWorkStore.dispatchRotation = rotation;
  fileSave(global.__anaWorkStore);
}

export async function nextInDispatchRotation(
  role: DispatchRole,
  candidates: number[],
  exclude: number[] = []
): Promise<number> {
  const sorted = [...new Set(candidates)].sort((a, b) => a - b);
  if (sorted.length === 0) throw new Error("nextInDispatchRotation: no candidates");

  const rotation = await readDispatchRotation();
  const start = rotation[role] % sorted.length;

  let picked = sorted[start];
  let nextCursor = (start + 1) % sorted.length;
  for (let i = 0; i < sorted.length; i++) {
    const idx = (start + i) % sorted.length;
    if (!exclude.includes(sorted[idx])) {
      picked = sorted[idx];
      nextCursor = (idx + 1) % sorted.length;
      break;
    }
  }

  await writeDispatchRotation({ ...rotation, [role]: nextCursor });
  return picked;
}

export async function resetWorks(): Promise<void> {
  if (await useNeon()) {
    try {
      const { kvDeleteByPrefix } = await import("./db");
      const removed = await kvDeleteByPrefix(WORK_KEY_PREFIX);
      console.log(`[workStore] reset — ${removed} work row(s) cleared`);
    } catch (e) {
      console.error("[workStore] resetWorks error:", e);
    }
  } else {
    fileSave({ works: {} });
    global.__anaWorkStore = { works: {} };
    console.log("[workStore] reset — all works cleared");
  }
  await writeDispatchRotation(DEFAULT_ROTATION);
  invalidateCache();
}

// ─── Vote helpers ─────────────────────────────────────────────────────────────

export function hasVoted(work: ANAWork, tokenId: number): boolean {
  return work.votes.some(v => v.tokenId === tokenId);
}

export function tallyVotes(work: ANAWork): {
  yes: number; no: number; abs: number; passed: boolean;
} {
  const yes = work.votes.filter(v => v.vote === "yes").length;
  const no  = work.votes.filter(v => v.vote === "no").length;
  const abs = work.votes.filter(v => v.vote === "abstain").length;
  // Memorials only: a tie (including 0/0 — nobody managed to vote at all, e.g.
  // a transient LLM outage) passes instead of failing. This is moderation of
  // an already-created piece, not a governance decision — the burn already
  // deserves its memorial; a real "no" majority is the only thing that should
  // send it back for a fresh attempt (see stepVoteTallied). Without this, an
  // outage where nobody casts a vote silently loops the same memorial forever
  // (observed in production: 5+ recreate cycles, always 0 yes / 0 no).
  // Standard governance works keep requiring a genuine yes-majority.
  const passed = work.isBurnMemorial ? yes >= no : yes > no;
  return { yes, no, abs, passed };
}

// ─── HTML builder (on-chain artifact) ────────────────────────────────────────

function escapeHtml(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function isHtmlArtwork(text: string): boolean {
  const t = text.trimStart();
  return t.startsWith("<!DOCTYPE") || t.startsWith("<html") || t.startsWith("<!doctype");
}

// Fetch a Normie's 40×40 face bitmap (GET /normie/{id}/pixels — a 1600-char
// "0101..." string) and pack it into 200 bytes, MSB-first, matching the same
// SSTORE2 format normies.art itself uses on-chain. Base64 of 200 bytes is
// ~268 chars — three portraits cost ~800 bytes total in the certificate,
// versus ~80-100KB for three full PNGs (which made eth_estimateGas fail
// outright on Base's public RPC — confirmed via local simulation; see
// commit history). The certificate's inline script (added once, shared by
// all three portraits) decodes this back into a tiny on-chain-rendered
// <canvas> face — same data, ~140x smaller than the rendered PNG.
async function fetchNormiePixelsB64(tokenId: number): Promise<string | null> {
  try {
    const res = await fetch(`https://api.normies.art/normie/${tokenId}/pixels`, { signal: AbortSignal.timeout(5_000) });
    if (!res.ok) return null;
    const bits = (await res.text()).replace(/[^01]/g, ""); // strip quotes/whitespace if API wraps it
    if (bits.length !== 1600) return null;

    const bytes = Buffer.alloc(200);
    for (let i = 0; i < 200; i++) {
      let byte = 0;
      for (let j = 0; j < 8; j++) byte = (byte << 1) | (bits[i * 8 + j] === "1" ? 1 : 0);
      bytes[i] = byte;
    }
    return bytes.toString("base64");
  } catch {
    return null;
  }
}

// Shared decoder, written once per certificate regardless of how many
// portraits it renders. Unpacks the 200-byte MSB-first bitmap back into a
// 40×40 monochrome <canvas>, scaled up via image-rendering:pixelated CSS.
const PORTRAIT_DECODER_SCRIPT = `
(function(){
  function draw(c){
    var b64=c.dataset.bitmap; if(!b64) return;
    var bin=atob(b64), ctx=c.getContext('2d'), img=ctx.createImageData(40,40), idx=0;
    for(var i=0;i<bin.length;i++){
      var byte=bin.charCodeAt(i);
      for(var j=7;j>=0;j--){
        var v=((byte>>j)&1)?20:240;
        img.data[idx*4]=v; img.data[idx*4+1]=v; img.data[idx*4+2]=v; img.data[idx*4+3]=255;
        idx++;
      }
    }
    ctx.putImageData(img,0,0);
  }
  document.querySelectorAll('.normie-portrait').forEach(draw);
})();
`.trim();

function portraitCanvas(bitmapB64: string | null, fallbackTokenId?: number): string {
  if (bitmapB64) {
    return `<canvas class="normie-portrait" data-bitmap="${bitmapB64}" width="40" height="40" style="width:64px;height:64px;image-rendering:pixelated;display:block"></canvas>`;
  }
  // Pixel fetch failed — fall back to the external URL so the card isn't empty.
  return fallbackTokenId
    ? `<img src="https://api.normies.art/normie/${fallbackTokenId}/image.png" style="width:64px;height:64px;image-rendering:pixelated;display:block">`
    : "";
}

